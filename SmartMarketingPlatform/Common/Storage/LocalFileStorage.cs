using Microsoft.Extensions.Options;
using SmartMarketingPlatform.Common.Options;

namespace SmartMarketingPlatform.Common.Storage;

public sealed class LocalFileStorage : IFileStorage
{
    private readonly string _root;

    public LocalFileStorage(IOptions<StorageOptions> options, IWebHostEnvironment environment)
    {
        _root = Path.GetFullPath(Path.Combine(environment.ContentRootPath, options.Value.MediaRoot));
        Directory.CreateDirectory(_root);
    }

    public async Task SaveAsync(string objectKey, Stream content, CancellationToken cancellationToken)
    {
        var path = PathOf(objectKey);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
        await content.CopyToAsync(file, cancellationToken);
    }

    public Task<Stream> OpenReadAsync(string objectKey, CancellationToken cancellationToken)
    {
        var path = PathOf(objectKey);
        if (!File.Exists(path))
            throw new FileNotFoundException("The stored file is missing.", objectKey);
        return Task.FromResult<Stream>(new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true));
    }

    public Task DeleteAsync(string objectKey, CancellationToken cancellationToken)
    {
        var path = PathOf(objectKey);
        if (File.Exists(path)) File.Delete(path);
        return Task.CompletedTask;
    }

    // Keys are generated by us ("{tenant}/{business}/{asset}.ext"), but the check below
    // still guarantees that no key can ever point outside the storage root.
    private string PathOf(string objectKey)
    {
        var path = Path.GetFullPath(Path.Combine(_root, objectKey));
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Invalid object key.");
        return path;
    }
}
